import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const generatedDir = path.join(root, 'src/content/exporter/generated')
const outputFile = path.join(generatedDir, 'html-assets.ts')

function readPackageFile(...parts) {
    return fs.readFileSync(path.join(root, 'node_modules', ...parts), 'utf8')
}

function readPackageAsset(...parts) {
    return fs.readFileSync(path.join(root, 'node_modules', ...parts))
}

function fontMimeType(fileName) {
    if (fileName.endsWith('.woff2')) return 'font/woff2'
    if (fileName.endsWith('.woff')) return 'font/woff'
    if (fileName.endsWith('.ttf')) return 'font/ttf'
    return 'application/octet-stream'
}

function inlineKatexFonts(css) {
    return css.replace(/url\(fonts\/([^)]+)\)/g, (_match, fileName) => {
        const bytes = readPackageAsset('katex', 'dist', 'fonts', fileName)
        return `url(data:${fontMimeType(fileName)};base64,${bytes.toString('base64')})`
    })
}

function stripCssComments(css) {
    return css.replace(/\/\*[\s\S]*?\*\//g, '')
}

const highlightCss = stripCssComments(readPackageFile('highlight.js', 'styles', 'github-dark.css'))
const katexCss = stripCssComments(inlineKatexFonts(readPackageFile('katex', 'dist', 'katex.min.css')))
const exportedHtmlStyles = `${highlightCss}\n${katexCss}`

fs.mkdirSync(generatedDir, { recursive: true })
fs.writeFileSync(
    outputFile,
    [
        '// Generated by scripts/generate-html-assets.mjs. Do not edit by hand.',
        `export const exportedHtmlStyles = ${JSON.stringify(exportedHtmlStyles)};`,
        '',
    ].join('\n'),
)
