// A portable message snapshot. Exporters never receive live host DOM nodes.
const OMIT = 'script, style, link, iframe, object, embed, button, input, textarea, select, [hidden], [aria-hidden="true"]:not(.katex-html), .sr-only, .gh-msg-select-check, [data-gh-owned]';
const TAGS = new Set('div span p br hr h1 h2 h3 h4 h5 h6 strong b em i u s del a blockquote pre code ul ol li table thead tbody tfoot tr th td img figure figcaption details summary sup sub math semantics annotation mrow mi mn mo mtext mspace msup msub msubsup mfrac msqrt mroot mtable mtr mtd mover munder munderover mpadded mstyle svg path line rect circle g'.split(' '));
const ATTRS = new Set('alt title colspan rowspan start reversed display encoding xmlns viewBox d fill stroke stroke-width x y x1 y1 x2 y2 width height cx cy r preserveAspectRatio'.split(' '));

function safeUrl(value, image = false) {
    try {
        const url = new URL(value, location.href);
        return ['https:', 'http:'].includes(url.protocol) || (image && /^(data:image\/(png|jpeg|webp|gif);|blob:)/i.test(value)) ? url.href : '';
    } catch { return ''; }
}

export function snapshotMessage(adapter, message, order) {
    const source = adapter.getMessageContent(message);
    const clone = source.cloneNode(true);
    clone.querySelectorAll(OMIT).forEach(node => node.remove());
    for (const node of [clone, ...clone.querySelectorAll('*')]) {
        if (!TAGS.has(node.localName)) {
            node.replaceWith(...node.childNodes);
            continue;
        }
        const formula = Boolean(node.closest('.katex, .katex-display'));
        for (const attr of [...node.attributes]) {
            if (attr.name === 'href' || attr.name === 'src') {
                const url = safeUrl(attr.value, attr.name === 'src');
                if (url) node.setAttribute(attr.name, url);
                else node.removeAttribute(attr.name);
            } else if (attr.name === 'class') {
                // KaTeX uses semantic classes; site utility classes must not leak into exports.
                if (!formula) node.removeAttribute('class');
            } else if (attr.name === 'style' && formula) {
                // Only the numeric layout properties generated by KaTeX are needed.
                const styles = [...node.style].filter(key => /^(height|width|min-width|top|left|right|bottom|vertical-align|margin-(left|right|top|bottom)|padding-(left|right|top|bottom)|border-bottom-width|font-size|line-height|position|display)$/.test(key));
                const values = styles.map(key => [key, node.style.getPropertyValue(key)]);
                node.removeAttribute('style');
                values.forEach(([key, value]) => { if (/^(?:-?[\d.]+(?:em|px|%)?|relative|absolute|inline-block|block)$/.test(value)) node.style.setProperty(key, value); });
            } else if (!ATTRS.has(attr.name)) node.removeAttribute(attr.name);
        }
        if (node.localName === 'img') {
            node.removeAttribute('width');
            node.removeAttribute('height');
        }
    }
    const plain = clone.cloneNode(true);
    plain.querySelectorAll('.katex').forEach(node => {
        const latex = node.querySelector('annotation[encoding="application/x-tex"]')?.textContent;
        if (latex) node.replaceWith(document.createTextNode(node.closest('.katex-display') ? `\n$$${latex}$$\n` : `$${latex}$`));
    });
    plain.querySelectorAll('br').forEach(node => node.replaceWith('\n'));
    plain.querySelectorAll('p, div, h1, h2, h3, h4, h5, h6, li, pre, tr').forEach(node => node.append('\n'));
    return {
        id: adapter.getMessageIdentity(message, order),
        role: adapter.getMessageRole(message),
        content: (plain.textContent || '').trim(),
        html: clone.innerHTML,
        order,
    };
}

export function snapshotMessages(adapter) {
    return adapter.getChatMessages().map((message, order) => snapshotMessage(adapter, message, order))
        .filter(message => ['user', 'assistant'].includes(message.role) && (message.content || message.html.includes('<img')));
}
